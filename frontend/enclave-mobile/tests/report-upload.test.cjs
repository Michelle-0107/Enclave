const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const mobile = path.resolve(__dirname, '..');
const fromMobile = createRequire(path.join(mobile, 'package.json'));
const ts = fromMobile('typescript');
class NativeFormData {
  constructor() { this.parts = []; }
  append(key, value) { this.parts.push([key, value]); }
  entries() { return this.parts[Symbol.iterator](); }
}
const sent = [];
let status = 201;
let data = { ticket_id: 'SYNTHETIC-1', data: [] };
let mode = 'response';
class FakeXHR {
  constructor() { this.headers = {}; this.abortCalls = 0; }
  open(method, url) { this.method = method; this.url = url; }
  setRequestHeader(key, value) { this.headers[key] = value; }
  send(body) {
    this.body = body;
    sent.push(this);
    queueMicrotask(() => {
      if (mode === 'network-error') { if (this.onerror) this.onerror(); return; }
      this.status = status;
      this.responseText = JSON.stringify(data);
      if (this.onload) this.onload();
    });
  }
  abort() { this.abortCalls++; if (this.onabort) this.onabort(); }
}
function load(file, dependencies = {}, extras = {}) {
  const output = ts.transpileModule(fs.readFileSync(file, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const mod = { exports: {} };
  vm.runInNewContext(output, {
    module: mod, exports: mod.exports,
    require(name) { if (name in dependencies) return dependencies[name]; throw Error(`Unexpected import ${name}`); },
    Blob, TextEncoder, Uint8Array, ArrayBuffer, FormData: NativeFormData,
    AbortController, XMLHttpRequest: FakeXHR,
    setTimeout, clearTimeout,
    process: { env: { EXPO_PUBLIC_API_URL: 'https://api.enclavehomes.app' } },
    ...extras,
  }, { filename: file });
  return mod.exports;
}
async function main() {
  let passed = 0;
  const converter = load(path.join(mobile, 'node_modules/expo/src/winter/fetch/convertFormData.ts'), {
    '../../utils/blobUtils': { blobToArrayBufferAsync: blob => blob.arrayBuffer() },
  });
  const form = new NativeFormData();
  form.append('description', 'Synthetic upload');
  form.append('latitude', '3.2254');
  form.append('longitude', '101.72925');
  form.append('file', { uri: 'file:///synthetic/photo.png', name: 'photo.png', type: 'image/png' });
  await assert.rejects(converter.convertFormDataAsync(form), /Unsupported FormDataPart implementation/);
  console.log('PASS: installed Expo SDK converter reproduces the URI upload failure'); passed++;
  const multipart = load(path.join(mobile, 'src/lib/multipartUpload.ts'));
  const options = () => ({ method: 'POST', body: form, signal: new AbortController().signal,
    headers: { Authorization: 'Bearer synthetic-token', Accept: 'application/json', 'Content-Type': 'multipart/form-data' } });
  const response = await multipart.uploadMultipart('https://api.enclavehomes.app/api/v1/reports', options());
  assert.equal(response.status, 201);
  assert.equal(sent[0].body, form);
  assert.equal(sent[0].headers.Authorization, 'Bearer synthetic-token');
  assert.equal(sent[0].headers['Content-Type'], undefined);
  assert.equal(sent[0].onload, null);
  console.log('PASS: file URI, auth and fields preserved; boundary generated by native transport'); passed++;
  const controller = new AbortController(); controller.abort();
  await assert.rejects(multipart.uploadMultipart('https://example.test', { ...options(), signal: controller.signal }), /aborted/);
  assert.equal(sent.length, 1);
  console.log('PASS: pre-aborted upload sends no request'); passed++;
  let fetched = 0;
  const api = load(path.join(mobile, 'src/lib/api.ts'), { './multipartUpload': multipart }, {
    fetch: async () => { fetched++; return { ok: true, status: 200, text: async () => JSON.stringify({ items: [], pagination: { has_more: false } }) }; },
  });
  const result = await api.reportsApi.submit('synthetic-token', form);
  assert.equal(result.ticket_id, 'SYNTHETIC-1');
  assert.equal(sent.at(-1).url, 'https://api.enclavehomes.app/api/v1/reports');
  assert.equal(fetched, 0);
  console.log('PASS: report API uses upload transport and the new backend URL'); passed++;
  await api.facilitiesApi.getAll('synthetic-token');
  assert.equal(fetched, 1);
  console.log('PASS: facility reads retain existing fetch transport'); passed++;
  for (const code of [401, 403, 413, 422, 503]) {
    status = code; data = { detail: 'Synthetic HTTP error' };
    const before = sent.length;
    await assert.rejects(api.reportsApi.submit('synthetic-token', form), e => e.status === code && e.message === data.detail);
    assert.equal(sent.length, before + 1);
  }
  console.log('PASS: HTTP/auth/file errors retain their status and uploads are never auto-retried'); passed++;
  const running = new AbortController();
  const pending = multipart.uploadMultipart('https://example.test', { ...options(), signal: running.signal });
  const current = sent.at(-1);
  running.abort();
  await assert.rejects(pending, /aborted/);
  assert.equal(current.abortCalls, 1);
  assert.equal(current.onload, null);
  console.log('PASS: cancellation stops an in-flight native upload and removes callbacks'); passed++;
  mode = 'network-error';
  const beforeError = sent.length;
  await assert.rejects(api.reportsApi.submit('synthetic-token', form), e => e.status === 0);
  assert.equal(sent.length, beforeError + 1);
  console.log('PASS: real network failures remain distinct from HTTP failures and are not retried'); passed++;
  console.log(`${passed} upload checks passed. No real report was submitted.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
