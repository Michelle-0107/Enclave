"""Build the address/name catalogue from existing OSM extracts, with no network calls."""
import argparse
import json
from pathlib import Path
from uuid import NAMESPACE_URL, uuid5
import xml.etree.ElementTree as ET


def build(repo: Path):
    registry = json.loads((repo / 'backend/data/service_areas.json').read_text(encoding='utf-8'))
    result = {}
    for area in registry['items']:
        source = repo / 'backend/data/demo_areas' / (area['id'] + '.osm')
        if not area['enabled'] or not source.is_file():
            continue
        root = ET.parse(source).getroot()
        nodes = {node.attrib['id']: (float(node.attrib['lon']), float(node.attrib['lat'])) for node in root.findall('node')}
        for kind in ('node', 'way'):
            for element in root.findall(kind):
                tags = {tag.attrib['k']: tag.attrib['v'] for tag in element.findall('tag')}
                address = tags.get('addr:full') or ', '.join(filter(None, [
                    ' '.join(filter(None, [tags.get('addr:housenumber'), tags.get('addr:street')])),
                    tags.get('addr:suburb'), tags.get('addr:postcode'), tags.get('addr:city')]))
                name = tags.get('name') or tags.get('name:en') or address
                if not name:
                    continue
                points = [nodes[element.attrib['id']]] if kind == 'node' else [nodes[n.attrib['ref']] for n in element.findall('nd') if n.attrib['ref'] in nodes]
                if not points:
                    continue
                longitude, latitude = (sum(p[i] for p in points) / len(points) for i in (0, 1))
                w, s, e, n = area['bbox']
                if not w <= longitude <= e or not s <= latitude <= n:
                    continue
                street = bool(tags.get('highway'))
                basis = ('Street reference point; choose the exact entrance on the map.' if street else
                         'Mapped point.' if kind == 'node' else 'Building or place reference point; check the entrance on the map.')
                identity = str(uuid5(NAMESPACE_URL, f"enclave:{area['id']}:osm:{kind}:{element.attrib['id']}"))
                result[identity] = dict(id=identity, area_id=area['id'], name=name[:250], address=(address or area['name'])[:1000],
                    longitude=longitude, latitude=latitude, position_basis=basis, source='openstreetmap')
    return sorted(result.values(), key=lambda row: (row['area_id'], row['name'], row['id']))


def write(repo: Path, output: Path):
    rows = build(repo)
    data = output / 'backend/data/map_places.json'
    data.parent.mkdir(parents=True, exist_ok=True)
    data.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    mobile = output / 'frontend/enclave-mobile/src/navigation/map-places.json'
    mobile.parent.mkdir(parents=True, exist_ok=True)
    mobile.write_text(json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    payload = json.dumps(rows, ensure_ascii=False).replace("'", "''")
    sql = "-- Generated by backend.tools.build_map_places from existing OpenStreetMap extracts (ODbL).\nBEGIN;\n"
    sql += "INSERT INTO public.map_places (id,area_id,name,address,longitude,latitude,position_basis,source)\n"
    sql += "SELECT id,area_id,name,address,longitude,latitude,position_basis,source FROM jsonb_to_recordset('\n" + payload + "\n'::jsonb) AS r(id uuid,area_id text,name text,address text,longitude double precision,latitude double precision,position_basis text,source text)\n"
    sql += "ON CONFLICT (id) DO UPDATE SET name=excluded.name,address=excluded.address,longitude=excluded.longitude,latitude=excluded.latitude,position_basis=excluded.position_basis;\nCOMMIT;\n"
    target = output / 'backend/sql/014_map_places_seed.sql'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(sql, encoding='utf-8')
    print(f'Built {len(rows)} named/address locations across {len({r["area_id"] for r in rows})} areas.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    write(args.repo, args.output or args.repo)
