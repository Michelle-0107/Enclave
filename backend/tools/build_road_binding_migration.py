"""Generate the canonical road-reference repair migration offline."""
import json
from pathlib import Path
from backend.navigation.road_bindings import road_reference_bindings

def generate():
    rows=sorted(road_reference_bindings().values(),key=lambda row:row['id'])
    payload=json.dumps(rows,ensure_ascii=True,separators=(',',':'))
    source="""-- Generated by python -m backend.tools.build_road_binding_migration.
-- Apply after 023. Canonical OSM IDs only; preserves report IDs, history and exact pins.
BEGIN;
WITH bindings AS (
 SELECT * FROM jsonb_to_recordset($road_bindings$"""+payload+"""$road_bindings$::jsonb)
 AS r(id uuid,latitude float8,longitude float8,section_id uuid,road_section jsonb)
)
UPDATE public.map_locations l SET metadata=l.metadata || jsonb_build_object(
 'report_target','road_reference','canonical_road_section_id',b.section_id,'road_section',b.road_section),updated_at=now()
FROM bindings b WHERE l.id=b.id AND l.kind='place' AND l.active
 AND abs(l.latitude-b.latitude)<0.000000001 AND abs(l.longitude-b.longitude)<0.000000001;

-- Existing road references were incorrectly inserted as 'other' by 022.
-- Do not reassign historical evidence, reporter counts, categories or maintenance tasks.
UPDATE public.community_facilities f SET facility_type='path_surface'
FROM public.map_locations l WHERE f.id=l.id AND f.facility_type='other'
 AND l.metadata->>'report_target'='road_reference'
 AND abs(f.latitude-l.latitude)<0.000000001 AND abs(f.longitude-l.longitude)<0.000000001;

DO $$ BEGIN
 IF to_regprocedure('public.enclave_community_issues_before_road_bindings(text,jsonb)') IS NULL THEN
  ALTER FUNCTION public.enclave_community_issues(text,jsonb) RENAME TO enclave_community_issues_before_road_bindings;
 END IF;
END $$;
CREATE OR REPLACE FUNCTION public.enclave_community_issues(p_action text,p_args jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
 IF p_action='open_place_issue' AND EXISTS(SELECT 1 FROM public.map_locations
  WHERE id=(p_args->>'facility_id')::uuid AND active AND metadata->>'report_target'='road_reference') THEN
  IF NOT EXISTS(SELECT 1 FROM public.residents r JOIN public.profiles p ON p.id=r.profile_id
   WHERE r.profile_id=(p_args->>'actor_id')::uuid AND r.status='active' AND r.verified_at IS NOT NULL
   AND p.role IN ('resident','management')) THEN RETURN jsonb_build_object('state','forbidden','place_reporting_version',1); END IF;
  RETURN jsonb_build_object('state','invalid','reason','choose_independent_road_section','place_reporting_version',1);
 END IF;
 RETURN public.enclave_community_issues_before_road_bindings(p_action,p_args);
EXCEPTION WHEN invalid_text_representation THEN RETURN jsonb_build_object('state','invalid');
END $$;
REVOKE ALL ON FUNCTION public.enclave_community_issues(text,jsonb),public.enclave_community_issues_before_road_bindings(text,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.enclave_community_issues(text,jsonb),public.enclave_community_issues_before_road_bindings(text,jsonb) TO service_role;
NOTIFY pgrst, 'reload schema';
COMMIT;
"""
    assert len(source.encode('utf-8')) < 900000
    return source

if __name__=='__main__':
    target=Path(__file__).resolve().parents[1]/'sql/024_road_reference_routing.sql'
    target.write_text(generate(),encoding='utf-8')
    print(f'Generated {target.name}: {len(road_reference_bindings())} canonical road references, {target.stat().st_size} bytes')
