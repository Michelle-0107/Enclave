"""Generate SQL Editor sized location seed files offline; never connect to a database."""
import json
from pathlib import Path
from backend.reports.road_sections import catalog
from backend.navigation.places import bundled_places

# Supabase Studio rejects SQL blobs above 0.98 MB. Include SQL wrappers in this budget.
MAX_SQL_BYTES = 900_000
HEADER = """-- Generated by python -m backend.tools.build_location_seed. OSM contributors / ODbL-1.0.
-- Apply after 020. Run ALL 021 files individually in filename order; do not concatenate in SQL Editor.
-- Rerunnable; preserve existing location names, positions and stable IDs.
BEGIN;
INSERT INTO public.map_locations(id,area_id,name,address,latitude,longitude,kind,source,position_basis,metadata)
SELECT id,area_id,name,address,latitude,longitude,kind,source,position_basis,metadata
FROM jsonb_to_recordset($locations$"""
FOOTER = """$locations$::jsonb) AS x(id uuid,area_id text,name text,address text,latitude float8,longitude float8,kind text,source text,position_basis text,metadata jsonb)
ON CONFLICT(id) DO UPDATE SET kind=CASE WHEN excluded.kind='road_section' THEN excluded.kind ELSE public.map_locations.kind END,
 metadata=CASE WHEN excluded.kind='road_section' THEN excluded.metadata ELSE public.map_locations.metadata END;
COMMIT;
"""

def catalogue_rows():
    rows = [dict(id=str(p.id),area_id=p.area_id,name=p.name,address=p.address,latitude=p.latitude,
        longitude=p.longitude,kind='place',source=p.source,position_basis=p.position_basis,metadata={}) for p in bundled_places()]
    rows += [dict(id=str(p.id),area_id=p.road_section.area_id,name=p.name,address='',latitude=p.latitude,
        longitude=p.longitude,kind='road_section',source='openstreetmap',position_basis='OSM road-section midpoint; not field verified',
        metadata={'road_section':p.road_section.model_dump(mode='json'),'facility_type':p.facility_type,'created_at':p.created_at.isoformat()}) for p in catalog().values()]
    rows.sort(key=lambda p:p['id'])
    assert len({p['id'] for p in rows}) == len(rows)
    return rows

def generate_files():
    rows=catalogue_rows()
    encoded=[json.dumps(row,ensure_ascii=False,separators=(',',':')) for row in rows]
    if any('$locations$' in row for row in encoded): raise ValueError('Seed delimiter appears in source data')
    chunks=[];current=[]
    # The 256-byte reserve covers part numbering and LF/CRLF conversion of SQL wrappers.
    overhead=len((HEADER+FOOTER+'[]').encode('utf-8'))+256
    size=overhead
    for row in encoded:
        extra=len(row.encode('utf-8'))+(1 if current else 0)
        if size+extra>MAX_SQL_BYTES and current:
            chunks.append(current);current=[];size=overhead
            extra=len(row.encode('utf-8'))
        if size+extra>MAX_SQL_BYTES: raise ValueError('A location exceeds the SQL Editor seed budget')
        current.append(row);size+=extra
    if current:chunks.append(current)
    if len(chunks)>25:raise ValueError('Too many seed parts; use a reviewed direct database import')
    result={}
    for index,chunk in enumerate(chunks):
        suffix='' if index==0 else chr(ord('a')+index)
        name=f'021{suffix}_shared_map_locations_seed.sql'
        result[name]=f'-- Seed part {index+1} of {len(chunks)}. Run the finalize file LAST.\n'+HEADER+'['+','.join(chunk)+']'+FOOTER
    # An explicit ID manifest catches missing chunks even when unrelated locations exist.
    manifest=','.join("'"+row['id']+"'" for row in rows)
    suffix=chr(ord('a')+len(chunks))
    result[f'021{suffix}_shared_map_locations_finalize.sql']=f"""-- Run LAST, after all 021 seed parts. Rerunnable. No location coordinates are changed.
BEGIN;
DO $seed_complete$
DECLARE loaded integer;
BEGIN
 SELECT count(*) INTO loaded FROM public.map_locations WHERE id=ANY(ARRAY[{manifest}]::uuid[]);
 IF loaded<>{len(rows)} THEN
  RAISE EXCEPTION 'Location seed incomplete: % of {len(rows)} records loaded. Run all 021 seed parts, then retry this finalize file.',loaded USING ERRCODE='23514';
 END IF;
END $seed_complete$;
-- Backfill labels only after the entire catalogue is available.
UPDATE public.reports SET location_id=NULL WHERE location_id IS NULL;
UPDATE public.reports r SET location_id=i.facility_id FROM public.community_issue_reports cr JOIN public.community_issues i ON i.id=cr.issue_id
WHERE cr.report_id=r.id AND EXISTS(SELECT 1 FROM public.map_locations l WHERE l.id=i.facility_id AND l.active
 AND public.enclave_location_distance(r.latitude,r.longitude,l.latitude,l.longitude)<=100);
NOTIFY pgrst,'reload schema';
COMMIT;
SELECT kind,count(*) FROM public.map_locations WHERE active GROUP BY kind ORDER BY kind;
"""
    if any(len(sql.encode('utf-8'))>MAX_SQL_BYTES for sql in result.values()):raise ValueError('Generated SQL exceeds its byte budget')
    return result

def generate():
    """Combined SQL for direct PostgreSQL clients only; SQL Editor must use individual files."""
    return ''.join(generate_files().values())

if __name__=='__main__':
    folder=Path(__file__).resolve().parents[1]/'sql'
    for name,sql in generate_files().items():
        (folder/name).write_text(sql,encoding='utf-8',newline='\n')
        print(name,len(sql.encode('utf-8')),'bytes')
